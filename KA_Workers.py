"""Prepare worker startup scripts for the shared v8 Lua bridge.

Copy this file beside KA_Bot.py. Run: python KA_Workers.py 4
This prepares files only; it does not launch emulators or run training.
"""

import argparse
from pathlib import Path


ROOT = Path(__file__).resolve().parent


def lua_string(value):
    """Quote a path for Lua, including spaces, quotes, and backslashes."""
    return '"' + ''.join(
        '\\' + character if character in ('"', '\\')
        else f'\\{ord(character):03d}' if ord(character) < 32
        else character
        for character in value
    ) + '"'


def prepare_worker(worker_id, root=ROOT, launch_token=""):
    """Return a startup script path without touching the worker's saved state.

    Worker 0 uses the single-bot bridge folder. Workers 1 onward use the
    numbered folders expected by KA_Parallel.py.
    """
    if type(worker_id) is not int or worker_id < 0:
        raise ValueError("Worker ID must be a nonnegative integer.")
    if launch_token and (len(launch_token) != 32 or any(c not in "0123456789abcdef" for c in launch_token)):
        raise ValueError("Launch token must be an empty string or 32 lowercase hexadecimal characters.")
    root = Path(root).resolve()
    if not (root / "KA_Bridge.lua").is_file():
        raise FileNotFoundError(f"Shared bridge missing: {root / 'KA_Bridge.lua'}")

    folder_name = "bridge" if worker_id == 0 else f"bridge_{worker_id}"
    (root / folder_name).mkdir(parents=True, exist_ok=True)
    startup_dir = root / "worker_startup"
    startup_dir.mkdir(parents=True, exist_ok=True)
    startup_path = startup_dir / f"worker_{worker_id}.lua"

    # A separate Lua runtime in each emulator receives its own configuration.
    # Only these small generated files contain absolute project paths.
    root_text = lua_string(root.as_posix().rstrip('/') + '/')
    startup_path.write_text(
        "-- Generated by KA_Workers.py; edit the shared bridge instead.\n"
        f"KA_BRIDGE_CONFIG = {{ root = {root_text}, worker_id = {worker_id}, launch_token = {lua_string(launch_token)} }}\n"
        'dofile(KA_BRIDGE_CONFIG.root .. "KA_Bridge.lua")\n',
        encoding="utf-8", newline="\n",
    )
    return startup_path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("count", type=int, nargs="?", default=4,
                        help="Number of parallel worker startup files (default: 4)")
    args = parser.parse_args()
    if args.count < 1:
        parser.error("count must be at least 1")
    print("Prepared single-bot startup:", prepare_worker(0))
    for worker_id in range(1, args.count + 1):
        print(f"Prepared worker {worker_id}:", prepare_worker(worker_id))
    print("Existing start.State files were preserved.")
    print("In the v8 coordinator, use workers N to select the active count.")


if __name__ == "__main__":
    main()
